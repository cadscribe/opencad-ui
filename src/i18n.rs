//! UI language (ADR 0011): English and German, shared by the foundation
//! and the app (the app's `i18n` module re-exports this one).
//!
//! Every module with user-visible text declares its own message table
//! with [`messages!`](crate::messages); each entry names a key and its
//! English and German text. The macro rejects an entry without both texts
//! at compile time (empty texts and differing `{0}`…`{9}` placeholders
//! too), so a table can never be half translated.
//!
//! ```ignore
//! opencad_ui::messages! {
//!     enum Msg {
//!         Grid: "Grid", "Raster";
//!         Saved: "Saved {0}", "{0} gespeichert";
//!     }
//! }
//! ui.label(tr(Msg::Grid));
//! ```
//!
//! The current language is per thread, set with [`set_lang`] on the UI
//! thread; other threads start with the language last set by
//! [`set_lang`] ([`set_thread_lang`] leaves that alone, for tests).

use std::cell::Cell;
use std::fmt::Display;
use std::sync::atomic::{AtomicU8, Ordering};

/// A UI language.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub enum Lang {
    #[default]
    En,
    De,
}

impl Lang {
    pub const ALL: [Lang; 2] = [Lang::En, Lang::De];

    /// Storage key of the setting.
    pub fn key(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::De => "de",
        }
    }

    pub fn from_key(key: &str) -> Option<Lang> {
        Lang::ALL.into_iter().find(|l| l.key() == key)
    }

    /// The language's own name (shown untranslated in menus).
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::De => "Deutsch",
        }
    }

    /// The language of a locale such as `de-DE`, `de_AT.UTF-8` or
    /// `en-US`; English unless it is German.
    pub fn from_locale(locale: &str) -> Lang {
        let primary = locale
            .split(['-', '_', '.', '@'])
            .next()
            .unwrap_or_default();
        if primary.eq_ignore_ascii_case("de") {
            Lang::De
        } else {
            Lang::En
        }
    }

    /// The decimal separator of the language.
    pub fn decimal(self) -> char {
        match self {
            Lang::En => '.',
            Lang::De => ',',
        }
    }
}

/// The language last set with [`set_lang`]: the start value of threads
/// that did not set one (background jobs).
static GLOBAL: AtomicU8 = AtomicU8::new(0);

thread_local! {
    static CURRENT: Cell<Lang> = Cell::new(match GLOBAL.load(Ordering::Relaxed) {
        1 => Lang::De,
        _ => Lang::En,
    });
}

/// The language of this thread.
pub fn lang() -> Lang {
    CURRENT.with(Cell::get)
}

/// Sets the language of this thread and the start value of new threads.
pub fn set_lang(lang: Lang) {
    set_thread_lang(lang);
    GLOBAL.store(lang as u8, Ordering::Relaxed);
}

/// Sets the language of this thread only (tests run in parallel threads).
pub fn set_thread_lang(lang: Lang) {
    CURRENT.with(|c| c.set(lang));
}

/// Runs `f` with this thread's language set to `lang`, then restores it.
pub fn with_lang<R>(lang: Lang, f: impl FnOnce() -> R) -> R {
    let before = self::lang();
    set_thread_lang(lang);
    let r = f();
    set_thread_lang(before);
    r
}

/// A message table generated by [`messages!`](crate::messages).
pub trait Message: Copy {
    fn text(self, lang: Lang) -> &'static str;
}

/// The text of `msg` in the current language.
pub fn tr<M: Message>(msg: M) -> &'static str {
    msg.text(lang())
}

/// The text of `msg` with `{0}`, `{1}`, … replaced by `args`.
pub fn trf<M: Message>(msg: M, args: &[&dyn Display]) -> String {
    fill(tr(msg), args)
}

/// Replaces the placeholders `{0}`…`{9}` of `template` by `args`.
pub fn fill(template: &str, args: &[&dyn Display]) -> String {
    use std::fmt::Write as _;
    let mut out = String::with_capacity(template.len() + 16);
    let mut rest = template;
    while let Some(i) = rest.find('{') {
        out.push_str(&rest[..i]);
        let tail = &rest[i..];
        let b = tail.as_bytes();
        if b.len() >= 3 && b[1].is_ascii_digit() && b[2] == b'}' {
            match args.get(usize::from(b[1] - b'0')) {
                Some(a) => {
                    let _ = write!(out, "{a}");
                }
                None => out.push_str(&tail[..3]),
            }
            rest = &tail[3..];
        } else {
            out.push('{');
            rest = &tail[1..];
        }
    }
    out.push_str(rest);
    out
}

/// Bit set of the placeholders `{0}`…`{9}` in `s`.
pub const fn placeholders(s: &str) -> u16 {
    let b = s.as_bytes();
    let mut set = 0u16;
    let mut i = 0;
    while i + 2 < b.len() {
        if b[i] == b'{' && b[i + 1].is_ascii_digit() && b[i + 2] == b'}' {
            set |= 1 << (b[i + 1] - b'0');
        }
        i += 1;
    }
    set
}

/// Compile-time check of a table entry: both texts present, same
/// placeholders.
pub const fn valid(en: &str, de: &str) -> bool {
    !en.is_empty() && !de.is_empty() && placeholders(en) == placeholders(de)
}

/// Declares a message table: an enum of keys with their English and
/// German texts. One table per module; it also adds a test that every
/// key has both texts.
#[macro_export]
macro_rules! messages {
    (
        $(#[$meta:meta])*
        $vis:vis enum $name:ident {
            $( $key:ident : $en:literal , $de:literal ; )*
        }
    ) => {
        $(#[$meta])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        $vis enum $name {
            $( $key, )*
        }

        impl $name {
            /// Every key of the table.
            #[allow(dead_code)]
            pub const ALL: &'static [$name] = &[$( $name::$key, )*];
        }

        impl $crate::i18n::Message for $name {
            fn text(self, lang: $crate::i18n::Lang) -> &'static str {
                let [en, de] = match self {
                    $( $name::$key => [$en, $de], )*
                };
                match lang {
                    $crate::i18n::Lang::En => en,
                    $crate::i18n::Lang::De => de,
                }
            }
        }

        const _: () = {
            $(
                assert!(
                    $crate::i18n::valid($en, $de),
                    concat!(
                        "message ", stringify!($key),
                        ": both texts must be non-empty and use the same placeholders"
                    ),
                );
            )*
        };

        #[cfg(test)]
        #[test]
        fn messages_are_translated() {
            use $crate::i18n::{Lang, Message as _};
            for &m in $name::ALL {
                for lang in Lang::ALL {
                    assert!(!m.text(lang).trim().is_empty(), "{m:?} in {lang:?}");
                }
            }
        }
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    crate::messages! {
        enum Msg {
            Hello: "Hello", "Hallo";
            Saved: "Saved {0} in {1} ms", "{0} in {1} ms gespeichert";
        }
    }

    #[test]
    fn lookup_follows_the_thread_language() {
        set_thread_lang(Lang::En);
        assert_eq!(tr(Msg::Hello), "Hello");
        with_lang(Lang::De, || {
            assert_eq!(tr(Msg::Hello), "Hallo");
            assert_eq!(
                trf(Msg::Saved, &[&"a.opencad", &12]),
                "a.opencad in 12 ms gespeichert"
            );
        });
        assert_eq!(trf(Msg::Saved, &[&"x", &3]), "Saved x in 3 ms");
    }

    #[test]
    fn fill_keeps_unknown_braces() {
        assert_eq!(fill("{a} {0} {1} {", &[&1]), "{a} 1 {1} {");
        assert_eq!(placeholders("{0} and {2}"), 0b101);
        assert!(!valid("{0}", "kein"));
        assert!(!valid("x", ""));
    }

    #[test]
    fn locales() {
        assert_eq!(Lang::from_locale("de-DE"), Lang::De);
        assert_eq!(Lang::from_locale("de_AT.UTF-8"), Lang::De);
        assert_eq!(Lang::from_locale("DE"), Lang::De);
        assert_eq!(Lang::from_locale("en-US"), Lang::En);
        assert_eq!(Lang::from_locale("fr-FR"), Lang::En);
        assert_eq!(Lang::from_locale(""), Lang::En);
        for l in Lang::ALL {
            assert_eq!(Lang::from_key(l.key()), Some(l));
        }
    }
}
